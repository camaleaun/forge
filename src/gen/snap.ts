import type { Ir } from '../ir/types.ts';
import type { I18nGenOptions } from './i18n-options.ts';
import type { PackageMeta } from './linux-desktop.ts';

const yaml = (text: string): string => JSON.stringify(text);

// snap/snapcraft.yaml: core24, strict confinement, amd64 and arm64. GTK 4 comes from the gnome
// extension's content snap, so it is a build dependency only. The network plug is needed only to download language packs.
export function generateSnapcraft(ir: Ir, appId: string, meta: PackageMeta = {}, i18n?: I18nGenOptions): string {
  const { name, version } = ir.app;
  const packs = i18n !== undefined && i18n.packs.length > 0;
  const download = packs && i18n.download;
  const description = meta.description ?? name;
  const buildPackages = ['libgtk-4-dev', ...(packs ? ['libsoup-3.0-dev'] : []), 'pkg-config'];
  const icon = ir.app.icon ? `icon: icons/hicolor/512x512/apps/${appId}.png\n` : '';
  return `# Generated by forge. Do not edit.
name: ${name}
base: core24
version: ${yaml(version)}
summary: ${yaml(description.replace(/\s+/g, ' ').replace(/\.$/, '').slice(0, 78))}
description: ${yaml(description.replace(/\s+/g, ' '))}
${icon}grade: ${version.includes('-') ? 'devel' : 'stable'}
confinement: strict
platforms:
  amd64:
  arm64:
apps:
  ${name}:
    command: usr/bin/${name}
    extensions: [gnome]
    desktop: usr/share/applications/${appId}.desktop
${download ? '    plugs: [network]\n' : ''}parts:
  ${name}:
    plugin: cmake
    source: .
    cmake-parameters:
      - -DCMAKE_INSTALL_PREFIX=/usr
    build-packages: [${buildPackages.join(', ')}]
`;
}
