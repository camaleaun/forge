import type { Ir } from '../ir/types.ts';
import type { I18nGenOptions } from './i18n-options.ts';

// GTK 4 window for the app (milestone L2 fills in the widget tree).
export function generateLinuxUi(ir: Ir, appId: string, _i18n?: I18nGenOptions): string {
  return `// Generated by forge. Do not edit.
#include <gtk/gtk.h>

#include "forge_app.hpp"

static const char* const APP_ID = "${appId}";

namespace forge_app {

int run_ui(int argc, char** argv) {
  (void)argc; (void)argv; (void)APP_ID;
  return 0;
}

}  // namespace forge_app
`;
}
