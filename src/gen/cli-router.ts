import type { Ir } from '../ir/types.ts';
import { textOf } from '../ir/text.ts';
import { cppString } from './escape.ts';
import { textExpr } from './text-cpp.ts';

const BUILTINS = [
  { flag: '--version', description: 'Print the version' },
  { flag: '--help', description: 'Show this help' },
];

function helpLines(ir: Ir): string[] {
  const options = [...ir.commands.map((command) => ({ flag: command.flag, description: textOf(command.description) })), ...BUILTINS];
  const width = Math.max(...options.map((option) => option.flag.length));
  return [
    `Usage: ${ir.app.name} [option]`,
    '',
    'Options:',
    ...options.map((option) => `  ${option.flag.padEnd(width)}  ${option.description}`),
  ];
}

// In i18n mode the option descriptions are rendered at run time, in the active language.
function i18nHelp(ir: Ir): string {
  // forge's own texts are messages when the table has them (generateProject adds them), so packs translate them.
  const builtin = (description: string): string =>
    ir.messages.some((m) => m.text === description && m.context === undefined) ? textExpr(ir, { kind: 'message', text: description }) : `Text(${cppString(description)})`;
  const options = [...ir.commands.map((command) => ({ flag: command.flag, text: textExpr(ir, command.description) })), ...BUILTINS.map((b) => ({ flag: b.flag, text: builtin(b.description) }))];
  const width = Math.max(...options.map((option) => option.flag.length));
  return [
    '  std::puts(' + cppString(`Usage: ${ir.app.name} [option]`) + ');',
    '  std::puts("");',
    '  std::puts("Options:");',
    ...options.map((option) => `  print_option(${cppString(`  ${option.flag.padEnd(width)}  `)}, ${option.text});`),
  ].join('\n');
}

export function generateCliRouter(ir: Ir, i18n = false): string {
  const help = i18n ? i18nHelp(ir) : helpLines(ir).map((line) => `  std::puts(${cppString(line)});`).join('\n');
  const printOption = i18n ? 'static void print_option(const char* label, const Text& description) {\n  std::printf("%s%s\\n", label, render(description).c_str());\n}\n\n' : '';
  const commands = ir.commands
    .map((command) => `  if (arg == ${cppString(command.flag)}) {\n    action_${command.handler}(out);\n    return 0;\n  }\n`)
    .join('');
  return `// Generated by forge. Do not edit.
#include "forge_app.hpp"

#include <cstdio>
#include <string_view>

namespace forge_app {

${printOption}static void print_help() {
${help}
}

int run_cli(int argc, char** argv, Surface& out) {
  (void)argc;
  const std::string_view arg = argv[1];
  if (arg == "--version") {
    std::puts(APP_VERSION);
    return 0;
  }
  if (arg == "--help") {
    print_help();
    return 0;
  }
${commands}  std::fprintf(stderr, "unknown option: %s (see --help)\\n", argv[1]);
  return 2;
}

}  // namespace forge_app
`;
}
