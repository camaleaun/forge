import type { Ir } from '../ir/types.ts';

// What package.json says about the app (all optional): shown in the launcher, the metainfo and the packages.
export type PackageMeta = { description?: string; license?: string; homepage?: string };

const oneLine = (text: string): string => text.replace(/\s+/g, ' ').trim();
const xml = (text: string): string => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// The freedesktop launcher entry. Its file name is the application id, which Wayland uses to bind the window to it.
export function generateDesktopEntry(ir: Ir, appId: string, meta: PackageMeta = {}): string {
  const { name } = ir.app;
  const comment = meta.description ? `Comment=${oneLine(meta.description)}\n` : '';
  const icon = ir.app.icon ? `Icon=${appId}\n` : '';
  return `# Generated by forge. Do not edit.
[Desktop Entry]
Type=Application
Name=${name}
${comment}Exec=${name}
${icon}Terminal=false
Categories=Utility;
`;
}

// AppStream metadata: software centers and `appstreamcli validate` read it.
export function generateMetainfo(ir: Ir, appId: string, meta: PackageMeta = {}): string {
  const { name } = ir.app;
  const description = meta.description ? oneLine(meta.description) : name;
  const summary = description.replace(/\.$/, '');
  const homepage = meta.homepage ? `  <url type="homepage">${xml(meta.homepage)}</url>\n` : '';
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by forge. Do not edit. -->
<component type="desktop-application">
  <id>${appId}</id>
  <name>${xml(name)}</name>
  <summary>${xml(summary)}</summary>
  <metadata_license>CC0-1.0</metadata_license>
  <project_license>${xml(meta.license ?? 'LicenseRef-proprietary')}</project_license>
  <description>
    <p>${xml(description)}</p>
  </description>
  <launchable type="desktop-id">${appId}.desktop</launchable>
${homepage}  <provides>
    <binary>${xml(name)}</binary>
  </provides>
  <content_rating type="oars-1.1"/>
</component>
`;
}
