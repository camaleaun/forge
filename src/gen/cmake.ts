import type { Ir } from '../ir/types.ts';
import { cppString } from './escape.ts';

// CMake quoted arguments share C-like escaping for the characters forge allows in names.
const q = cppString;

export function generateCmake(ir: Ir, i18n = false): string {
  const { name, version } = ir.app;
  // CMake's project(VERSION) only accepts numeric x.y.z.w: keep the prerelease suffix elsewhere.
  const numericVersion = version.replace(/[-+].*$/, '');
  const icon = ir.app.icon;
  // The .icns goes to Contents/Resources and Info.plist names it (without the extension).
  const iconResource = icon ? `set_source_files_properties(${icon} PROPERTIES MACOSX_PACKAGE_LOCATION Resources)\n` : '';
  const i18nSources = i18n ? '\n  messages.cpp\n  i18n.cpp\n  i18n_macos.mm' : '';
  // i18n apps carry the Foundation loader: -Oz, no Objective-C exception tables and no local symbols keep them small.
  const optimize = i18n ? '-Oz' : '-Os';
  const objcxxFlags = i18n ? '-fobjc-arc -fno-objc-exceptions' : '-fobjc-arc';
  const linkFlags = i18n ? '-Wl,-dead_strip -Wl,-x' : '-Wl,-dead_strip';
  const iconProperty = icon ? `\n  MACOSX_BUNDLE_ICON_FILE ${icon.replace(/\.icns$/, '')}` : '';
  return `# Generated by forge. Do not edit.
cmake_minimum_required(VERSION 3.25)

option(FORGE_UNIVERSAL "Build a universal (arm64 + x86_64) binary" OFF)
if(FORGE_UNIVERSAL)
  set(CMAKE_OSX_ARCHITECTURES "arm64;x86_64")
else()
  set(CMAKE_OSX_ARCHITECTURES "arm64")
endif()

if(NOT CMAKE_BUILD_TYPE)
  set(CMAKE_BUILD_TYPE Release)
endif()

project(${name} VERSION ${numericVersion} LANGUAGES CXX OBJCXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_OBJCXX_STANDARD 20)
set(CMAKE_OBJCXX_STANDARD_REQUIRED ON)

add_executable(${name} MACOSX_BUNDLE
  main.cpp
  actions.cpp
  cli_router.cpp
  ui_macos.mm${i18nSources}${icon ? `\n  ${icon}` : ''})
${iconResource}
target_compile_options(${name} PRIVATE
  ${optimize} -fno-exceptions -fno-rtti -Wall -Wextra
  $<$<COMPILE_LANGUAGE:OBJCXX>:${objcxxFlags}>)
target_link_options(${name} PRIVATE ${linkFlags})
target_link_libraries(${name} PRIVATE "-framework Cocoa")

set_target_properties(${name} PROPERTIES${iconProperty}
  MACOSX_BUNDLE_BUNDLE_NAME ${q(name)}
  MACOSX_BUNDLE_GUI_IDENTIFIER ${q(`local.forge.${name}`)}
  MACOSX_BUNDLE_BUNDLE_VERSION ${q(version)}
  MACOSX_BUNDLE_SHORT_VERSION_STRING ${q(version)})

install(TARGETS ${name} BUNDLE DESTINATION .)

set(CPACK_GENERATOR DragNDrop)
set(CPACK_PACKAGE_NAME ${q(name)})
set(CPACK_PACKAGE_VERSION ${q(version)})
set(CPACK_DMG_VOLUME_NAME ${q(name)})

option(FORGE_STYLED_DMG "Style the .dmg window with the Finder (needs automation permission)" ON)
if(FORGE_STYLED_DMG)
  execute_process(
    COMMAND tiffutil -cathidpicheck "\${CMAKE_SOURCE_DIR}/dmg/background.png" "\${CMAKE_SOURCE_DIR}/dmg/background@2x.png"
            -out "\${CMAKE_BINARY_DIR}/background.tiff"
    RESULT_VARIABLE forge_tiff_result)
  if(forge_tiff_result EQUAL 0)
    set(CPACK_DMG_BACKGROUND_IMAGE "\${CMAKE_BINARY_DIR}/background.tiff")
    set(CPACK_DMG_DS_STORE_SETUP_SCRIPT "\${CMAKE_SOURCE_DIR}/dmg/setup.applescript")
  endif()
endif()

include(CPack)
`;
}
