import type { Ir } from '../ir/types.ts';
import { glassCompileArgs } from '../icon/glass.ts';
import { cppString } from './escape.ts';

// CMake quoted arguments share C-like escaping for the characters forge allows in names.
const q = cppString;

export interface CmakeOptions {
  // AppIcon.icon (Liquid Glass) sits next to the sources: compile it with Xcode 26's actool when available.
  glassIcon?: boolean;
}

// Configure-time lookup of actool and its version (short-bundle-version follows the Xcode version, e.g. 26.6).
const GLASS_PROBE = `# Liquid Glass icon: needs Xcode 26's actool; without it the classic icon (if any) is used.
set(forge_glass_icon OFF)
execute_process(COMMAND xcrun --find actool RESULT_VARIABLE forge_actool_found OUTPUT_QUIET ERROR_QUIET)
if(forge_actool_found EQUAL 0)
  execute_process(COMMAND xcrun actool --version OUTPUT_VARIABLE forge_actool_version ERROR_QUIET)
  if(forge_actool_version MATCHES "short-bundle-version</key>[ \\t\\r\\n]*<string>([0-9]+)")
    if(CMAKE_MATCH_1 GREATER_EQUAL 26)
      set(forge_glass_icon ON)
    endif()
  endif()
endif()
`;

function glassSetup(icon: string | undefined): string {
  const dir = '${CMAKE_BINARY_DIR}/glass-icon';
  const args = glassCompileArgs({ iconPath: '${CMAKE_SOURCE_DIR}/AppIcon.icon', outputDir: dir, partialPlist: `${dir}/partial.plist` })
    .map((arg) => (arg.includes('$') ? `"${arg}"` : arg));
  const classic = icon
    ? `  set(forge_icon_files ${icon})\n  set_source_files_properties(${icon} PROPERTIES MACOSX_PACKAGE_LOCATION Resources)\n`
    : '  set(forge_icon_files)\n';
  return `${GLASS_PROBE}
if(forge_glass_icon)
  file(GLOB_RECURSE forge_icon_layers CONFIGURE_DEPENDS "\${CMAKE_SOURCE_DIR}/AppIcon.icon/*")
  add_custom_command(
    OUTPUT "${dir}/Assets.car" "${dir}/AppIcon.icns"
    COMMAND \${CMAKE_COMMAND} -E make_directory "${dir}"
    COMMAND xcrun actool ${args.join(' ')}
    DEPENDS \${forge_icon_layers}
    COMMENT "Compiling the Liquid Glass icon"
    VERBATIM)
  set(forge_icon_files "${dir}/Assets.car" "${dir}/AppIcon.icns")
  set_source_files_properties(\${forge_icon_files} PROPERTIES MACOSX_PACKAGE_LOCATION Resources GENERATED TRUE)
  # CMake's own Info.plist template plus CFBundleIconName, which names the icon in Assets.car.
  file(READ "\${CMAKE_ROOT}/Modules/MacOSXBundleInfo.plist.in" forge_plist)
  string(REPLACE "</dict>\\n</plist>" "\\t<key>CFBundleIconName</key>\\n\\t<string>AppIcon</string>\\n</dict>\\n</plist>" forge_plist "\${forge_plist}")
  file(WRITE "\${CMAKE_BINARY_DIR}/Info.plist.in" "\${forge_plist}")
else()
${classic}endif()
`;
}

function glassTarget(name: string, icon: string | undefined): string {
  const iconFile = `set_target_properties(${name} PROPERTIES MACOSX_BUNDLE_ICON_FILE AppIcon)`;
  const withGlass = `set_target_properties(${name} PROPERTIES MACOSX_BUNDLE_INFO_PLIST "\${CMAKE_BINARY_DIR}/Info.plist.in")`;
  return `if(forge_glass_icon)
  ${iconFile}
  ${withGlass}
${icon ? `else()\n  ${iconFile}\n` : ''}endif()

`;
}

export function generateCmake(ir: Ir, i18n = false, options: CmakeOptions = {}): string {
  const { name, version } = ir.app;
  // CMake's project(VERSION) only accepts numeric x.y.z.w: keep the prerelease suffix elsewhere.
  const numericVersion = version.replace(/[-+].*$/, '');
  const icon = ir.app.icon;
  // The .icns goes to Contents/Resources and Info.plist names it (without the extension).
  const glass = options.glassIcon === true;
  const iconResource = icon && !glass ? `set_source_files_properties(${icon} PROPERTIES MACOSX_PACKAGE_LOCATION Resources)\n` : '';
  const i18nSources = i18n ? '\n  messages.cpp\n  i18n.cpp\n  i18n_common.cpp\n  i18n_macos.mm' : '';
  // i18n apps carry the Foundation loader: -Oz, no Objective-C exception tables and no local symbols keep them small.
  const optimize = i18n ? '-Oz' : '-Os';
  const objcxxFlags = i18n ? '-fobjc-arc -fno-objc-exceptions' : '-fobjc-arc';
  const linkFlags = i18n ? '-Wl,-dead_strip -Wl,-x' : '-Wl,-dead_strip';
  const iconProperty = icon && !glass ? `\n  MACOSX_BUNDLE_ICON_FILE ${icon.replace(/\.icns$/, '')}` : '';
  return `# Generated by forge. Do not edit.
cmake_minimum_required(VERSION 3.25)

option(FORGE_UNIVERSAL "Build a universal (arm64 + x86_64) binary" OFF)
if(FORGE_UNIVERSAL)
  set(CMAKE_OSX_ARCHITECTURES "arm64;x86_64")
else()
  set(CMAKE_OSX_ARCHITECTURES "arm64")
endif()

if(NOT CMAKE_BUILD_TYPE)
  set(CMAKE_BUILD_TYPE Release)
endif()

project(${name} VERSION ${numericVersion} LANGUAGES CXX OBJCXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_OBJCXX_STANDARD 20)
set(CMAKE_OBJCXX_STANDARD_REQUIRED ON)
${glass ? '\n' + glassSetup(icon) + '\n' : '\n'}add_executable(${name} MACOSX_BUNDLE
  main.cpp
  actions.cpp
  cli_router.cpp
  ui_macos.mm${i18nSources}${glass ? '\n  ${forge_icon_files}' : icon ? `\n  ${icon}` : ''})
${iconResource}
target_compile_options(${name} PRIVATE
  ${optimize} -fno-exceptions -fno-rtti -Wall -Wextra
  $<$<COMPILE_LANGUAGE:OBJCXX>:${objcxxFlags}>)
target_link_options(${name} PRIVATE ${linkFlags})
target_link_libraries(${name} PRIVATE "-framework Cocoa")

set_target_properties(${name} PROPERTIES${iconProperty}
  MACOSX_BUNDLE_BUNDLE_NAME ${q(name)}
  MACOSX_BUNDLE_GUI_IDENTIFIER ${q(`local.forge.${name}`)}
  MACOSX_BUNDLE_BUNDLE_VERSION ${q(version)}
  MACOSX_BUNDLE_SHORT_VERSION_STRING ${q(version)})

${glass ? glassTarget(name, icon) : ''}install(TARGETS ${name} BUNDLE DESTINATION .)

set(CPACK_GENERATOR DragNDrop)
set(CPACK_PACKAGE_NAME ${q(name)})
set(CPACK_PACKAGE_VERSION ${q(version)})
set(CPACK_DMG_VOLUME_NAME ${q(name)})

option(FORGE_STYLED_DMG "Style the .dmg window with the Finder (needs automation permission)" ON)
if(FORGE_STYLED_DMG)
  execute_process(
    COMMAND tiffutil -cathidpicheck "\${CMAKE_SOURCE_DIR}/dmg/background.png" "\${CMAKE_SOURCE_DIR}/dmg/background@2x.png"
            -out "\${CMAKE_BINARY_DIR}/background.tiff"
    RESULT_VARIABLE forge_tiff_result)
  if(forge_tiff_result EQUAL 0)
    set(CPACK_DMG_BACKGROUND_IMAGE "\${CMAKE_BINARY_DIR}/background.tiff")
    set(CPACK_DMG_DS_STORE_SETUP_SCRIPT "\${CMAKE_SOURCE_DIR}/dmg/setup.applescript")
  endif()
endif()

include(CPack)
`;
}
