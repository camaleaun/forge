import type { Ir } from '../ir/types.ts';
import { cppString } from './escape.ts';

const q = cppString;

// CMake project for the Linux target (milestones L3, L7 and L8 add flags, install rules and CPack).
export function generateCmakeLinux(ir: Ir, _i18n = false): string {
  const { name, version } = ir.app;
  const numericVersion = version.replace(/[-+].*$/, '');
  return `# Generated by forge. Do not edit.
cmake_minimum_required(VERSION 3.25)

if(NOT CMAKE_BUILD_TYPE)
  set(CMAKE_BUILD_TYPE Release)
endif()

project(${name} VERSION ${numericVersion} LANGUAGES CXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

find_package(PkgConfig REQUIRED)
pkg_check_modules(GTK4 REQUIRED IMPORTED_TARGET gtk4)

add_executable(${name}
  main.cpp
  actions.cpp
  cli_router.cpp
  ui_linux.cpp)
target_compile_options(${name} PRIVATE -Os -fno-exceptions -fno-rtti -Wall -Wextra)
target_link_libraries(${name} PRIVATE PkgConfig::GTK4)
set_target_properties(${name} PROPERTIES OUTPUT_NAME ${q(name)})
`;
}
