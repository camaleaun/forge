import { DMG_ICON_CENTERS, DMG_ICON_SIZE, DMG_TITLE_BAR, DMG_WINDOW } from '../dmg/layout.ts';
import type { Ir } from '../ir/types.ts';

const WINDOW_LEFT = 200;
const WINDOW_TOP = 120;

// AppleScript that CPack runs against the mounted image: it lays the Finder window out
// (fixed size, no toolbar, background picture, app icon left, Applications right).
export function generateDmgSetupScript(ir: Ir): string {
  const name = ir.app.name;
  const right = WINDOW_LEFT + DMG_WINDOW.width;
  const bottom = WINDOW_TOP + DMG_WINDOW.height + DMG_TITLE_BAR;
  const [appX, appY] = DMG_ICON_CENTERS.app;
  const [applicationsX, applicationsY] = DMG_ICON_CENTERS.applications;
  return `-- Generated by forge. Do not edit.
tell application "Finder"
  tell disk "${name}"
    open
    set current view of container window to icon view
    set toolbar visible of container window to false
    set statusbar visible of container window to false
    set the bounds of container window to {${WINDOW_LEFT}, ${WINDOW_TOP}, ${right}, ${bottom}}
    set viewOptions to the icon view options of container window
    set arrangement of viewOptions to not arranged
    set icon size of viewOptions to ${DMG_ICON_SIZE}
    set text size of viewOptions to 13
    set background picture of viewOptions to file ".background:background.tiff"
    set position of item "${name}.app" of container window to {${appX}, ${appY}}
    set position of item "Applications" of container window to {${applicationsX}, ${applicationsY}}
    close
    open
    update without registering applications
    delay 2
  end tell
end tell
`;
}
