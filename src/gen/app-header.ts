import type { Ir } from '../ir/types.ts';
import { cppString } from './escape.ts';
import { navigationUsed, stepIds } from './steps.ts';

export function generateAppHeader(ir: Ir, i18n = false, http = false): string {
  const stateIds = ir.states.map((state) => state.id).join(', ');
  const stateEnum = stateIds ? `{ ${stateIds} }` : '{}';
  const actions = ir.handlers.map((handler) => `void action_${handler.id}(Surface& out);\n`).join('');
  const include = (i18n ? '\n#include "i18n_loader.hpp"\n\n#define FORGE_I18N 1\n' : '') + (http ? '\n#define FORGE_HTTP 1\n' : '');
  const ids = stepIds(ir);
  const stepEnum = ids.length > 0 ? `enum class StepId { ${ids.join(', ')} };\n\n` : '';
  const used = navigationUsed(ir);
  const navigation = [
    used.next && '  virtual void go_next() {}\n',
    used.back && '  virtual void go_back() {}\n',
    used.step && '  virtual void go_step(StepId id) { (void)id; }\n',
    used.quit && '  virtual void quit() {}\n',
  ].filter(Boolean).join('');
  const setter = i18n ? 'const Text& text' : 'const char* text';
  return `// Generated by forge. Do not edit.
#pragma once
${include}
namespace forge_app {

constexpr const char* APP_VERSION = ${cppString(ir.app.version)};

enum class StateId ${stateEnum};

${stepEnum}struct Surface {
  virtual ~Surface() = default;
  virtual void set_state(StateId id, ${setter}) = 0;
${navigation}};

${actions}
int run_cli(int argc, char** argv, Surface& out);
int run_ui(int argc, char** argv);

}  // namespace forge_app
`;
}
