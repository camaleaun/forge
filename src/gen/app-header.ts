import type { Ir } from '../ir/types.ts';
import { cppString } from './escape.ts';

export function generateAppHeader(ir: Ir): string {
  const stateIds = ir.states.map((state) => state.id).join(', ');
  const stateEnum = stateIds ? `{ ${stateIds} }` : '{}';
  const actions = ir.handlers.map((handler) => `void action_${handler.id}(Surface& out);\n`).join('');
  return `// Generated by forge. Do not edit.
#pragma once

namespace forge_app {

constexpr const char* APP_VERSION = ${cppString(ir.app.version)};

enum class StateId ${stateEnum};

struct Surface {
  virtual ~Surface() = default;
  virtual void set_state(StateId id, const char* text) = 0;
};

${actions}
int run_cli(int argc, char** argv, Surface& out);
int run_ui(int argc, char** argv);

}  // namespace forge_app
`;
}
