import type { Ir } from '../ir/types.ts';
import { cppString } from './escape.ts';
import type { I18nGenOptions } from './i18n-options.ts';

const nullable = (value: string | undefined): string => (value === undefined ? 'nullptr' : cppString(value));

// The message table, the pinned language packs and the app constants the loader reads.
export function generateMessagesCpp(ir: Ir, options: I18nGenOptions): string {
  const messages = ir.messages.length > 0 ? ir.messages.map((m) => `    {${nullable(m.context)}, ${cppString(m.text)}, ${nullable(m.plural)}},`) : ['    {nullptr, nullptr, nullptr},'];
  const packs = options.packs.map((p) => `    {${cppString(p.tag)}, ${cppString(p.file)}, ${cppString(p.sha256)}, ${p.size}},`);
  return `// Generated by forge. Do not edit.
#include "i18n_loader.hpp"

namespace forge_app {

const MessageDef MESSAGES[] = {
${messages.join('\n')}
};
const int MSG_COUNT = ${ir.messages.length};

const PackDef PACKS[] = {
${packs.join('\n')}
};
const int PACK_COUNT = ${options.packs.length};

const char* const PACK_BASE_URL = ${cppString(options.baseUrl)};
const char* const APP_ID = ${cppString(options.appId)};
const bool DOWNLOAD_ENABLED = ${options.download};
const bool MENU_ENABLED = ${options.menu};

}  // namespace forge_app
`;
}
