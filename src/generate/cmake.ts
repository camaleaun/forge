import type { Spec } from '../spec/types.ts';
import { cppString } from './escape.ts';

// CMake quoted arguments share C-like escaping for the characters forge allows in names.
const q = cppString;

export function generateCmake(spec: Spec): string {
  const { name, version } = spec.app;
  // CMake's project(VERSION) only accepts numeric x.y.z.w: keep the prerelease suffix elsewhere.
  const numericVersion = version.replace(/[-+].*$/, '');
  return `# Generated by forge. Do not edit.
cmake_minimum_required(VERSION 3.25)

option(FORGE_UNIVERSAL "Build a universal (arm64 + x86_64) binary" OFF)
if(FORGE_UNIVERSAL)
  set(CMAKE_OSX_ARCHITECTURES "arm64;x86_64")
else()
  set(CMAKE_OSX_ARCHITECTURES "arm64")
endif()

if(NOT CMAKE_BUILD_TYPE)
  set(CMAKE_BUILD_TYPE Release)
endif()

project(${name} VERSION ${numericVersion} LANGUAGES CXX OBJCXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_OBJCXX_STANDARD 20)
set(CMAKE_OBJCXX_STANDARD_REQUIRED ON)

add_executable(${name} MACOSX_BUNDLE
  main.cpp
  actions.cpp
  cli_router.cpp
  ui_macos.mm)

target_compile_options(${name} PRIVATE
  -Os -fno-exceptions -fno-rtti -Wall -Wextra
  $<$<COMPILE_LANGUAGE:OBJCXX>:-fobjc-arc>)
target_link_options(${name} PRIVATE -Wl,-dead_strip)
target_link_libraries(${name} PRIVATE "-framework Cocoa")

set_target_properties(${name} PROPERTIES
  MACOSX_BUNDLE_BUNDLE_NAME ${q(name)}
  MACOSX_BUNDLE_GUI_IDENTIFIER ${q(`local.forge.${name}`)}
  MACOSX_BUNDLE_BUNDLE_VERSION ${q(version)}
  MACOSX_BUNDLE_SHORT_VERSION_STRING ${q(version)})

install(TARGETS ${name} BUNDLE DESTINATION .)

set(CPACK_GENERATOR DragNDrop)
set(CPACK_PACKAGE_NAME ${q(name)})
set(CPACK_PACKAGE_VERSION ${q(version)})
include(CPack)
`;
}
