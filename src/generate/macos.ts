import type { Spec, Widget } from '../spec/types.ts';
import { objcString } from './escape.ts';

// Cocoa's origin is the bottom-left corner, forge.json's is the top-left.
function frame(widget: Widget, windowHeight: number): string {
  const y = windowHeight - widget.y - widget.height;
  return `NSMakeRect(${widget.x}, ${y}, ${widget.width}, ${widget.height})`;
}

function emitWidget(widget: Widget, index: number, windowHeight: number): string {
  const v = `w_${widget.id}`;
  if (widget.type === 'label') {
    return `    NSTextField* ${v} = [[NSTextField alloc] initWithFrame:${frame(widget, windowHeight)}];
    [${v} setStringValue:${objcString(widget.text)}];
    [${v} setBezeled:NO];
    [${v} setDrawsBackground:NO];
    [${v} setEditable:NO];
    [${v} setSelectable:NO];
    [content addSubview:${v}];
    g_surface.labels[static_cast<int>(WidgetId::${widget.id})] = ${v};
`;
  }
  return `    NSButton* ${v} = [[NSButton alloc] initWithFrame:${frame(widget, windowHeight)}];
    [${v} setTitle:${objcString(widget.text)}];
    [${v} setBezelStyle:NSBezelStyleRounded];
    [${v} setTag:${index}];
    [${v} setTarget:target];
    [${v} setAction:@selector(invoke:)];
    [content addSubview:${v}];
`;
}

export function generateMacosUi(spec: Spec): string {
  const { window, widgets } = spec;
  const cases = widgets
    .map((widget, index) => (widget.type === 'button'
      ? `    case ${index}:\n      action_${widget.action}(g_surface);\n      break;\n`
      : ''))
    .join('');
  const blocks = widgets.map((widget, index) => emitWidget(widget, index, window.height)).join('\n');
  return `// Generated by forge. Do not edit.
#import <Cocoa/Cocoa.h>

#include "forge_app.hpp"

using namespace forge_app;

namespace {

constexpr int kWidgetCount = ${widgets.length};

class CocoaSurface : public Surface {
 public:
  NSTextField* labels[kWidgetCount] = {};

  void set_text(WidgetId id, const char* text) override {
    NSTextField* label = labels[static_cast<int>(id)];
    if (label != nil) [label setStringValue:[NSString stringWithUTF8String:text]];
  }
};

CocoaSurface g_surface;

}  // namespace

@interface ForgeTarget : NSObject <NSApplicationDelegate>
- (void)invoke:(NSButton*)sender;
@end

@implementation ForgeTarget

- (void)invoke:(NSButton*)sender {
  switch (sender.tag) {
${cases}  }
}

- (BOOL)applicationShouldTerminateAfterLastWindowClosed:(NSApplication*)app {
  return YES;
}

@end

int forge_app::run_ui(int argc, char** argv) {
  (void)argc;
  (void)argv;
  @autoreleasepool {
    NSApplication* app = [NSApplication sharedApplication];
    [app setActivationPolicy:NSApplicationActivationPolicyRegular];
    ForgeTarget* target = [[ForgeTarget alloc] init];
    [app setDelegate:target];

    NSMenu* menubar = [[NSMenu alloc] init];
    NSMenuItem* appItem = [[NSMenuItem alloc] init];
    [menubar addItem:appItem];
    NSMenu* appMenu = [[NSMenu alloc] init];
    [appMenu addItemWithTitle:${objcString(`Quit ${spec.app.name}`)} action:@selector(terminate:) keyEquivalent:@"q"];
    [appItem setSubmenu:appMenu];
    [app setMainMenu:menubar];

    NSWindow* window = [[NSWindow alloc]
        initWithContentRect:NSMakeRect(0, 0, ${window.width}, ${window.height})
                  styleMask:(NSWindowStyleMaskTitled | NSWindowStyleMaskClosable)
                    backing:NSBackingStoreBuffered
                      defer:NO];
    [window setTitle:${objcString(window.title)}];
    [window center];
    NSView* content = [window contentView];

${blocks}
    [window makeKeyAndOrderFront:nil];
    [app activateIgnoringOtherApps:YES];
    [app run];
  }
  return 0;
}
`;
}
