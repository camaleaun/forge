import type { Spec } from '../spec/types.ts';
import { cppString } from './escape.ts';

export function generateAppHeader(spec: Spec, actionNames: string[]): string {
  const widgetIds = spec.widgets.map((widget) => widget.id).join(', ');
  const actions = actionNames.map((name) => `void action_${name}(Surface& out);\n`).join('');
  return `// Generated by forge. Do not edit.
#pragma once

namespace forge_app {

constexpr const char* APP_VERSION = ${cppString(spec.app.version)};

enum class WidgetId { ${widgetIds} };

struct Surface {
  virtual ~Surface() = default;
  virtual void set_text(WidgetId id, const char* text) = 0;
};

${actions}
int run_cli(int argc, char** argv, Surface& out);
int run_ui(int argc, char** argv);

}  // namespace forge_app
`;
}
