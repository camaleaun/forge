import type { Effect } from '../actions/trace.ts';
import { cppString } from './escape.ts';

const WIDGET_ID_PREFIX = 'WidgetId::';

function emitEffect(effect: Effect): string {
  return `  out.set_text(${WIDGET_ID_PREFIX}${effect.target}, ${cppString(effect.text)});`;
}

export function generateActionsCpp(effects: Record<string, Effect[]>): string {
  const functions = Object.entries(effects)
    .map(([name, list]) => `void action_${name}(Surface& out) {\n${list.map(emitEffect).join('\n')}\n}\n`)
    .join('\n');
  return `// Generated by forge. Do not edit.
#include "forge_app.hpp"

namespace forge_app {

${functions}
}  // namespace forge_app
`;
}
